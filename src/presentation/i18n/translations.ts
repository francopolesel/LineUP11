const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, es };

export const translationKeys = Object.keys(en) as TranslationKey[];

export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
